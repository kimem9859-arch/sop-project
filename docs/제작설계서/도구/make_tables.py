def main(out="tbl", include_hold=False):
    os.makedirs(out, exist_ok=True)
    for name, cap, header, rows, ratios, align, bf, hl in T:
        if name in UNUSED:
            print(f"{name:24s} ❌ 미사용 — 도식이 본체")
            continue
        if name in HOLD and not include_hold:
            print(f"{name:24s} ⏸ 보류 — 건너뜀")
            continue
        h = os.path.join(out, name + ".html")
        fs = build(header, rows, h, ratios=ratios, caption=cap, align=align,
                   bold_first=bf, hilite_col=hl)
        render(h, 1920, 1080, os.path.join(out, name + ".png"))
        os.remove(h)
        flag = "  ⚠️ 글자가 작다 — 분할 검토" if fs < 17 else ""
        print(f"{name:24s} {fs:2d}px{flag}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "tbl")
